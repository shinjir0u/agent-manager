CREATE TABLE IF NOT EXISTS sale_executive_status (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	status VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS roles (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	role VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS tokens (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	token VARCHAR(255),
	expiration BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS admins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL,
    email VARCHAR(255) UNIQUE NOT NULL,
    password VARCHAR(255),
    role BIGINT NOT NULL,
    token BIGINT,
    FOREIGN KEY (role) REFERENCES roles (id),
    FOREIGN KEY (token) REFERENCES tokens (id)
);

CREATE TABLE IF NOT EXISTS sale_executives (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL,
    email VARCHAR(255) UNIQUE NOT NULL,
    password VARCHAR(255),
    phone_number VARCHAR(50),
    role BIGINT NOT NULL,
    status BIGINT,
    token BIGINT,
    FOREIGN KEY (role) REFERENCES roles (id),
    FOREIGN KEY (status) REFERENCES sale_executive_status (id),
    FOREIGN KEY (token) REFERENCES tokens (id)
);

CREATE TABLE IF NOT EXISTS registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_name VARCHAR(255),
    phone_number VARCHAR(50),
    registered_at TIMESTAMP,
    sale_executive_id BIGINT,
    FOREIGN KEY (sale_executive_id) REFERENCES sale_executives(id)
);